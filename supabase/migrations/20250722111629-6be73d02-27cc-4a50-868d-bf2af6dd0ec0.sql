-- Now insert/update corresponding records in public.users table
DO $$
DECLARE
    master_user_id uuid;
    admin_user_id uuid;
    employee_user_id uuid;
    vendor_user_id uuid;
    company_id uuid;
BEGIN
    -- Get user IDs from auth.users
    SELECT id INTO master_user_id FROM auth.users WHERE email = 'master@arnetwork.com';
    SELECT id INTO admin_user_id FROM auth.users WHERE email = 'admin@arnetwork.com';
    SELECT id INTO employee_user_id FROM auth.users WHERE email = 'employee@arnetwork.com';
    SELECT id INTO vendor_user_id FROM auth.users WHERE email = 'vendor@arnetwork.com';
    
    -- Get company ID
    SELECT id INTO company_id FROM companies WHERE name = 'AR Network Solutions' LIMIT 1;
    
    -- Insert or update public.users records
    INSERT INTO public.users (id, email, full_name, role, company_id) 
    VALUES 
      (master_user_id, 'master@arnetwork.com', 'Master Admin', 'master_admin', null),
      (admin_user_id, 'admin@arnetwork.com', 'Company Admin', 'company_admin', company_id),
      (employee_user_id, 'employee@arnetwork.com', 'Test Employee', 'employee', company_id),
      (vendor_user_id, 'vendor@arnetwork.com', 'Test Vendor', 'vendor', null)
    ON CONFLICT (id) DO UPDATE SET
      email = EXCLUDED.email,
      full_name = EXCLUDED.full_name,
      role = EXCLUDED.role,
      company_id = EXCLUDED.company_id;
END $$;